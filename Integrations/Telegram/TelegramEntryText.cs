    // All authored/dynamic text is plain text. Only this renderer owns Telegram HTML.
    public static string RenderHelp(string intro, IEnumerable<HelpSection> sections) =>
        WebUtility.HtmlEncode(intro) + "\n\n" + string.Join("\n\n", sections.Select(section =>
            $"<b>{WebUtility.HtmlEncode(section.Title)}</b>\n<blockquote expandable>{WebUtility.HtmlEncode(section.Body)}</blockquote>"));

    public static string Help { get; } = RenderHelp(HelpIntro, HelpSections);
    public static TelegramEntryMessage? ForPrivateCommand(string command) => command switch
    {
        "/start" => new(Start),
        "/help" => new(Help, ParseMode.Html),
        _ => null
    };

